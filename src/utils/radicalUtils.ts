/**
 * Parses multi-radical descriptions like:
 * "亻 (person) + 女 (woman)" -> ["亻 (person)", "女 (woman)"]
 * "冂 (border) / 见 (see)" -> ["冂 (border)", "见 (see)"]
 * "亻 / 女" -> ["亻", "女"]
 */
export function splitCompoundRadicals(radicalStr?: string): string[] {
  if (!radicalStr) return [];
  const normalized = radicalStr.trim();
  if (!normalized) return [];

  // Split by +, /, ;, comma, or 'và'
  const parts = normalized.split(/\s*(?:\+|\/|;|,\s*|、|\bvà\b|\band\b)\s*/i);
  return parts.filter(Boolean);
}

/**
 * Returns accurate Radical information for any given single Chinese character:
 * 1. Checks specific character mapping
 * 2. Parses compound radical strings if index provided
 * 3. Falls back to detecting Kangxi radical components inside the character
 */
export function getCharRadical(
  activeChar: string,
  wordRadical?: string,
  charIndex: number = 0
): { radical: string; name?: string; meaning?: string; shortDisplay: string; fullDisplay: string } {
  const trimmedChar = activeChar ? activeChar.trim() : '';

  // 1. Direct character exact match in database
  if (trimmedChar && HANZI_RADICAL_MAP[trimmedChar]) {
    const info = HANZI_RADICAL_MAP[trimmedChar];
    return {
      radical: info.radical,
      name: info.name,
      meaning: info.meaning,
      shortDisplay: info.radical,
      fullDisplay: `${info.radical} (${info.name} - ${info.meaning})`,
    };
  }

  // 2. Parse from wordRadical if it is a compound expression
  const parts = splitCompoundRadicals(wordRadical);
  if (parts.length > charIndex && parts[charIndex]) {
    const rawPart = parts[charIndex].trim();
    // Check if rawPart starts with a known radical glyph (e.g. "女 (woman)")
    const firstChar = rawPart.charAt(0);
    const kangxiMatch = KANGXI_RADICALS_LIST.find((k) => k.radical === firstChar);
    if (kangxiMatch) {
      return {
        radical: kangxiMatch.radical,
        name: kangxiMatch.name,
        meaning: kangxiMatch.meaning,
        shortDisplay: kangxiMatch.radical,
        fullDisplay: `${kangxiMatch.radical} (${kangxiMatch.name} - ${kangxiMatch.meaning})`,
      };
    }
    return {
      radical: firstChar || rawPart,
      shortDisplay: firstChar || rawPart,
      fullDisplay: rawPart,
    };
  }

  // 3. Fallback: Search if any Kangxi radical is visually contained in activeChar
  if (trimmedChar) {
    // Check exact radical itself
    const exactKangxi = KANGXI_RADICALS_LIST.find((k) => k.radical === trimmedChar);
    if (exactKangxi) {
      return {
        radical: exactKangxi.radical,
        name: exactKangxi.name,
        meaning: exactKangxi.meaning,
        shortDisplay: exactKangxi.radical,
        fullDisplay: `${exactKangxi.radical} (${exactKangxi.name} - ${exactKangxi.meaning})`,
      };
    }

    // Check sub-radical inside character
    for (const kr of KANGXI_RADICALS_LIST) {
      if (kr.radical.length === 1 && trimmedChar.includes(kr.radical)) {
        return {
          radical: kr.radical,
          name: kr.name,
          meaning: kr.meaning,
          shortDisplay: kr.radical,
          fullDisplay: `${kr.radical} (${kr.name} - ${kr.meaning})`,
        };
      }
    }
  }

  // 4. Default fallback
  const fallbackRadical = (wordRadical && parts[0]) ? parts[0] : '—';
  return {
    radical: fallbackRadical,
    shortDisplay: fallbackRadical,
    fullDisplay: fallbackRadical,
  };
}

