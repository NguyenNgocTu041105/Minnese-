/**
 * TypeScript Interfaces for Multi-LLM Waterfall Generator, Validator, and Batch CLI
 */

export type ProviderOperationalStatus =
  | 'eligible'
  | 'quota_exhausted'
  | 'billing_blocked'
  | 'capacity_exhausted'
  | 'free_tier_not_eligible'
  | 'disabled';

export interface LLMProviderConfig {
  id: string;
  name: string;
  displayName: string;
  baseUrl: string;
  models: string[];
  getApiKey: () => string | undefined;
  authHeaderPrefix?: string;
  isLocal?: boolean;
  isFreeTier?: boolean;
  supportsStrictJsonSchema?: boolean;
  status?: ProviderOperationalStatus;
  statusReason?: string;
  paidModeAllowed?: boolean;
  maxBudgetUsd?: number;
  maxTokenLimit?: number;
}

export type QuestionLifecycleStatus =
  | 'processing'
  | 'pending'
  | 'approved'
  | 'rejected'
  | 'validation_failed'
  | 'disabled'
  | 'archived';

export type DifficultyTier = 'tier1_difficult' | 'tier2_very_difficult' | 'tier3_challenge';

export type TrapType =
  | 'near_synonym'
  | 'collocation'
  | 'grammar_rule'
  | 'context_scope'
  | 'word_order'
  | 'near_synonym_collocation'
  | 'word_order_trap'
  | 'complement_boundary'
  | 'ba_bei_structure'
  | 'clause_logic'
  // IELTS & HSK 3.0 cognitive trap types
  | 'anti_verbatim'
  | 'self_correction'
  | 'rhetorical_attitude'
  | 'numerical_twist';

export interface DistractorRationaleItem {
  optionIdx: number;
  optionText: string;
  rationaleVi: string;
  rationale_vi?: string;
  isCorrect?: boolean;
}

export type CandidateDistractorRationale =
  | DistractorRationaleItem
  | {
      option_idx: number;
      option_text: string;
      rationale_vi: string;
      is_correct?: boolean;
    };

export interface CandidateQuestion {
  id?: string;
  stem: string;
  /** Raw completed Chinese sentence as generated by LLM provider (undefined if omitted in raw LLM output, "" if empty string). */
  raw_completed_stem?: string;
  /** Completed Chinese sentence (canonical substitution or normalized completed stem). */
  completed_stem?: string;
  /** Deterministic backend placeholder substitution: stem with the placeholder replaced by options[answer_idx]. */
  canonical_completed_stem?: string;
  options: string[];
  answer_idx: number;
  explanation_vi: string;
  /** Provider-supplied short translation/overview used only to compose explanation_vi. */
  explanation_summary_vi?: string;
  /** Provider-supplied Vietnamese justification for the selected answer. */
  answer_rationale_vi?: string;
  level: number;
  skill: 'listening' | 'reading' | 'writing';
  part_type: string;
  pinyin?: string | null;
  stem_pinyin?: string | null;
  options_pinyin?: string[];
  passage_pinyin?: string | null;
  audio_text_pinyin?: string | null;
  illustration_theme?: string | null;
  options_images?: string[];
  passage?: string | null;
  audio_text?: string | null;
  transcript?: string | null;
  audio_url?: string | null;
  audio_playback?: number;
  vocab_tags?: string[];
  tested_vocab?: string[];
  topic?: string | null;
  difficulty?: string;
  status?: QuestionLifecycleStatus | string;
  provider_used?: string;
  content_hash?: string;
  near_duplicate_signature?: string;
  is_imported?: boolean;

  // Milestone 2 Linguistic & Distractor Depth:
  difficulty_tier?: DifficultyTier;
  trap_type?: TrapType | string;
  target_grammar?: string;
  target_vocabulary?: string;
  distractor_rationales?: Record<string, string> | CandidateDistractorRationale[];
  naturalness_review?: {
    status: 'natural' | 'unnatural';
    rationale_vi: string;
  };
}

export interface ValidationResult {
  valid: boolean;
  errors: string[];
  warnings?: string[];
  jaccardSimilarity?: number;
  matchedExistingStem?: string;
  contentHash?: string;
  nearDuplicateSignature?: string;
  lifecycleStatus?: QuestionLifecycleStatus;
  verifiedTestedVocab?: string[];
  verifiedContextualVocab?: string[];
}

export interface GenerationOptions {
  level: number;
  skill?: 'listening' | 'reading' | 'writing' | 'all';
  count: number;
  provider?: string;
  part_type?: string;
  topic?: string;
  mock?: boolean;
  timeoutMs?: number;
  difficulty_tier?: DifficultyTier;
  target_grammar?: string;
  trap_type?: TrapType | string;
  freeOnly?: boolean;
  maxCompletionTokens?: number;
}

export interface BatchRunSummary {
  batchId: string;
  level: number;
  skill: string;
  countRequested: number;
  countGenerated: number;
  countSavedPending: number;
  countRejectedValidator: number;
  providerUsed: string;
  modelUsed: string;
  fallbackOccurred: boolean;
  fallbackLog: string[];
  executionTimeMs: number;
  rejectedReasons: Record<string, number>;
  timestamp: string;
}
